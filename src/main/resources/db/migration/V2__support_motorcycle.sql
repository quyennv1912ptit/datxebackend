-- V2__support_motorcycle.sql
-- Hỗ trợ xe máy (MOTORCYCLE) bên cạnh ô tô (CAR).
-- Đặt tại: src/main/resources/db/migration/V2__support_motorcycle.sql
--
-- Đã có sẵn từ V1 (không cần làm lại):
--   vehicles.vehicle_type, rides.vehicle_type, pricing_rules.vehicle_type
--   đều đã cho phép 'CAR' và 'MOTORCYCLE'.
-- Quy ước kiểu số trong DB là 'MANUAL' / 'AUTO' (không phải 'AUTOMATIC').
-- Không sửa file này sau khi đã chạy (Flyway kiểm tra checksum).
-- =====================================================================


-- ---------------------------------------------------------------------
-- 1. vehicles: dung tích xi-lanh (chỉ xe máy dùng)
-- ---------------------------------------------------------------------
ALTER TABLE vehicles ADD COLUMN IF NOT EXISTS engine_cc integer;

ALTER TABLE vehicles ADD CONSTRAINT chk_vehicles_engine_cc
    CHECK (engine_cc IS NULL OR (engine_cc > 0 AND vehicle_type = 'MOTORCYCLE'));


-- ---------------------------------------------------------------------
-- 2. rides.vehicle_type phải khớp với loại xe của vehicle_id
--    (chặn chuyến ghi "MOTORCYCLE" nhưng gắn với xe ô tô và ngược lại).
--    Hệ quả: không đổi được vehicles.vehicle_type khi xe đã có chuyến.
-- ---------------------------------------------------------------------
ALTER TABLE vehicles ADD CONSTRAINT uq_vehicles_id_vehicle_type UNIQUE (id, vehicle_type);

ALTER TABLE rides ADD CONSTRAINT fk_rides_vehicle_type
    FOREIGN KEY (vehicle_id, vehicle_type) REFERENCES vehicles (id, vehicle_type);


-- ---------------------------------------------------------------------
-- 3. driver_vehicle_skills: tài xế lái được loại xe + kiểu số nào
--    Chỉ được ghép chuyến khi verified = true (admin duyệt bằng lái)
-- ---------------------------------------------------------------------
CREATE TABLE driver_vehicle_skills (
                                       id            bigint      PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
                                       created_at    timestamptz NOT NULL DEFAULT now(),
                                       updated_at    timestamptz NOT NULL DEFAULT now(),
                                       driver_id     bigint      NOT NULL REFERENCES drivers (id) ON DELETE CASCADE,
                                       vehicle_type  varchar(30) NOT NULL,
                                       transmission  varchar(30) NOT NULL,
                                       license_class varchar(10),
                                       verified      boolean     NOT NULL DEFAULT false,
                                       CONSTRAINT chk_dvs_vehicle_type CHECK (vehicle_type IN ('CAR', 'MOTORCYCLE')),
                                       CONSTRAINT chk_dvs_transmission CHECK (transmission IN ('MANUAL', 'AUTO')),
                                       CONSTRAINT uq_dvs_driver_skill UNIQUE (driver_id, vehicle_type, transmission)
);

CREATE INDEX idx_dvs_lookup
    ON driver_vehicle_skills (vehicle_type, transmission, driver_id)
    WHERE verified;

