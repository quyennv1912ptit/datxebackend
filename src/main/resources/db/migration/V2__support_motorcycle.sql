-- ---------------------------------------------------------------------
-- 4. pricing_rules: mỗi loại xe đúng một rule đang hoạt động
--    Trước đây vehicle_type = NULL nghĩa là "giá chung cho mọi loại xe", khiến
--    xe máy bị tính giá ô tô. Từ nay bắt buộc có loại xe.
-- ---------------------------------------------------------------------
DROP INDEX IF EXISTS uq_pricing_rules_active;

-- Nếu đã có rule CAR đang bật thì rule chung (NULL) bị tắt, tránh trùng sau khi đổi
UPDATE pricing_rules n
SET active = false
WHERE n.vehicle_type IS NULL AND n.active
  AND EXISTS (SELECT 1 FROM pricing_rules c WHERE c.vehicle_type = 'CAR' AND c.active);

UPDATE pricing_rules SET vehicle_type = 'CAR' WHERE vehicle_type IS NULL;
ALTER TABLE pricing_rules ALTER COLUMN vehicle_type SET NOT NULL;

CREATE UNIQUE INDEX uq_pricing_rules_active ON pricing_rules (vehicle_type) WHERE active;

-- night_start / night_end phải có cùng lúc; dòng chỉ có một đầu coi như chưa cấu hình giờ đêm
UPDATE pricing_rules
SET night_start = NULL, night_end = NULL
WHERE (night_start IS NULL) <> (night_end IS NULL);

ALTER TABLE pricing_rules ADD CONSTRAINT pricing_rules_night_pair_check
    CHECK ((night_start IS NULL) = (night_end IS NULL));

-- Số phút chờ miễn phí trước khi tính per_minute_waiting
ALTER TABLE pricing_rules ADD COLUMN IF NOT EXISTS free_waiting_minutes integer NOT NULL DEFAULT 0;
ALTER TABLE pricing_rules ADD CONSTRAINT pricing_rules_free_waiting_check
    CHECK (free_waiting_minutes >= 0);

-- Rule xe máy: sao chép từ rule ô tô làm khung nhưng để active = false.
-- PHẢI sửa giá thật rồi mới bật. Chưa bật thì đặt xe máy báo "không có bảng giá"
-- (chủ ý: tốt hơn là tính nhầm giá ô tô).
INSERT INTO pricing_rules
(vehicle_type, base_fare, min_fare, per_km, per_minute_waiting, return_fee_for_driver,
 night_start, night_end, night_surcharge_percent, free_waiting_minutes, active)
SELECT 'MOTORCYCLE', c.base_fare, c.min_fare, c.per_km, c.per_minute_waiting, c.return_fee_for_driver,
       c.night_start, c.night_end, c.night_surcharge_percent, c.free_waiting_minutes, false
FROM pricing_rules c
WHERE c.vehicle_type = 'CAR' AND c.active
  AND NOT EXISTS (SELECT 1 FROM pricing_rules m WHERE m.vehicle_type = 'MOTORCYCLE')
    LIMIT 1;

