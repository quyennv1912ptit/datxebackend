CREATE TABLE ride_create_idempotency (
    customer_id bigint NOT NULL,
    idempotency_key varchar(128) NOT NULL,
    request_hash varchar(64) NOT NULL,
    ride_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT pk_ride_create_idempotency PRIMARY KEY (customer_id, idempotency_key),
    CONSTRAINT uq_ride_create_idempotency_ride UNIQUE (ride_id),
    CONSTRAINT fk_ride_create_idempotency_ride_customer
        FOREIGN KEY (ride_id, customer_id) REFERENCES rides (id, customer_id)
);

CREATE TABLE ride_dispatch_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ride_id bigint NOT NULL UNIQUE REFERENCES rides (id),
    created_at timestamptz NOT NULL DEFAULT now(),
    available_at timestamptz NOT NULL DEFAULT now(),
    locked_until timestamptz,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    delivered_at timestamptz,
    last_error text
);

CREATE INDEX idx_ride_dispatch_outbox_due
    ON ride_dispatch_outbox (available_at, id)
    WHERE delivered_at IS NULL;

CREATE INDEX idx_rides_status_updated_at
    ON rides (status, updated_at);

CREATE TABLE account_cleanup_outbox (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    firebase_uid text NOT NULL,
    owner_role varchar(16) NOT NULL CHECK (owner_role IN ('CUSTOMER', 'DRIVER')),
    owner_id bigint NOT NULL,
    cloudinary_public_ids text[] NOT NULL DEFAULT '{}',
    created_at timestamptz NOT NULL DEFAULT now(),
    available_at timestamptz NOT NULL DEFAULT now(),
    locked_until timestamptz,
    attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
    completed_at timestamptz,
    last_error text,
    CONSTRAINT uq_account_cleanup_owner UNIQUE (owner_role, owner_id)
);

CREATE INDEX idx_account_cleanup_outbox_due
    ON account_cleanup_outbox (available_at, id)
    WHERE completed_at IS NULL;
